import net.minecraftforge.registries.RegistryObject;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Spartan Weaponry: Hexalia. Two tiers crafted the way Hexalia makes its own weapons, at the Ritual Table:
 * - Ancient: Hexalia's own Ancient tool tier (the Cinderhew/Kelpweave tier), center Ancient Seed + earth offerings.
 * - Celestial: a step above diamond, center Celestial Crystal + the Ancient weapon and the other three nodes.
 * Recipes and assets are generated by tools/gen_assets.py.
 */
@Mod(SpartanWeaponryHexalia.MODID)
public class SpartanWeaponryHexalia extends SpartanAddon {
    public static final String MODID = "spartanweaponryhexalia";

    public static final WeaponMap WEAPONS = new WeaponMap();
    public static final DeferredRegister<Item> ITEMS = itemRegister(MODID);
    public static final DeferredRegister<WeaponTrait> TRAITS = traitRegister(MODID);
    public static final DeferredRegister<CreativeModeTab> TABS = tabRegister(MODID);

    /** Celestial tier: harvest 3, 1400 uses, speed 8.5, +3.5 damage, enchantability 25, Celestial Crystal repair. */
    public static final Tier CELESTIAL_TIER = new Tier() {
        @Override public int getUses() { return 1400; }
        @Override public float getSpeed() { return 8.5F; }
        @Override public float getAttackDamageBonus() { return 3.5F; }
        @Override public int getLevel() { return 3; }
        @Override public int getEnchantmentValue() { return 25; }
        @Override public Ingredient getRepairIngredient() {
            Item crystal = ForgeRegistries.ITEMS.getValue(new ResourceLocation("hexalia", "celestial_crystal"));
            return crystal == null ? Ingredient.EMPTY : Ingredient.of(crystal);
        }
    };

    // Levelled traits: plain type + setLevel; Spartan Toolkit registers them as "<type>_<level>".

    /** Rootbind I/II: roots (Slowness II) whatever the weapon hits, for the magnitude in seconds. */
    private static RegistryObject<WeaponTrait> rootbind(int level, float seconds) {
        BetterWeaponTrait trait = new BetterWeaponTrait("rootbind", MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return String.format(Locale.US, "Hits root the target (Slowness II) for %s seconds", trimmed(this.magnitude));
            }

            @Override
            public void onHitEntity(WeaponMaterial material, ItemStack stack, LivingEntity target, LivingEntity attacker, Entity projectile) {
                root(target, this.magnitude);
            }

            @Override
            public void onRangedHitEntity(WeaponMaterial material, ItemStack stack, LivingEntity target, LivingEntity attacker, Entity projectile) {
                root(target, this.magnitude);
            }
        };
        trait.setMagnitude(seconds).setLevel(level);
        trait.setMelee().setRanged().setThrowing();
        return registerTrait(TRAITS, trait);
    }

    public static final RegistryObject<WeaponTrait> ROOTBIND_1 = rootbind(1, 1.5F);
    public static final RegistryObject<WeaponTrait> ROOTBIND_2 = rootbind(2, 3.0F);

    /** Moonlit: Celestial weapons hit harder at night. */
    public static final RegistryObject<WeaponTrait> MOONLIT = registerTrait(TRAITS,
        new BetterWeaponTrait("moonlit", MODID, TraitQuality.POSITIVE) {
            @Override
            public String getDescription() {
                return String.format(Locale.US, "+%d%% damage at night", Math.round(this.magnitude * 100.0F - 100.0F));
            }

            @Override
            public float modifyDamageDealt(WeaponMaterial material, float baseDamage, DamageSource source, LivingEntity attacker, LivingEntity victim) {
                return isNight(attacker) ? baseDamage * this.magnitude : baseDamage;
            }

            @Override
            public float modifyRangedDamageDealt(WeaponMaterial material, float baseDamage, DamageSource source, LivingEntity attacker, LivingEntity victim) {
                return isNight(attacker) ? baseDamage * this.magnitude : baseDamage;
            }
        }.setMagnitude(1.35F).setMelee().setRanged().setThrowing());

    public static final List<SpartanMaterial> MATERIALS = new ArrayList<>();

    public static final SpartanMaterial ANCIENT = material("ancient", ModToolTiers.ANCIENT, Rarity.UNCOMMON, ROOTBIND_1);
    public static final SpartanMaterial CELESTIAL = material("celestial", CELESTIAL_TIER, Rarity.RARE, ROOTBIND_2, MOONLIT);

    public static final RegistryObject<CreativeModeTab> TAB = registerTab(TABS, MODID,
        () -> WEAPONS.get(CELESTIAL, WeaponType.LONGSWORD).get(),
        (parameters, output) -> ITEMS.getEntries().forEach(item -> output.accept(item.get())));

    @SafeVarargs
    private static SpartanMaterial material(String name, Tier tier, Rarity rarity, RegistryObject<WeaponTrait>... traits) {
        TagKey<Item> repair = ItemTags.create(new ResourceLocation(MODID, "repair/" + name));
        SpartanMaterial material = new SpartanMaterial(name, MODID, tier, repair, traits).setRarity(rarity);
        MATERIALS.add(material);
        return material;
    }

    private static void root(LivingEntity target, float seconds) {
        target.addEffect(new MobEffectInstance(MobEffects.MOVEMENT_SLOWDOWN, Math.round(seconds * 20.0F), 1));
    }

    private static boolean isNight(LivingEntity entity) {
        return entity != null && entity.level().dimensionType().hasSkyLight() && entity.level().isNight();
    }

    private static String trimmed(float value) {
        return value == Math.floor(value) ? Integer.toString((int) value) : Float.toString(value);
    }

    public SpartanWeaponryHexalia() {
        IEventBus bus = FMLJavaModLoadingContext.get().getModEventBus();
        registerSpartanWeapons(ITEMS);
        ITEMS.register(bus);
        TRAITS.register(bus);
        TABS.register(bus);
    }

    @Override
    public String modid() {
        return MODID;
    }

    @Override
    public List<SpartanMaterial> getMaterials() {
        return MATERIALS;
    }

    @Override
    public WeaponMap getWeaponMap() {
        return WEAPONS;
    }
}
